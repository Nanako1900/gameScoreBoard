-- EDG 信誉分 — PostgreSQL schema, P3a: a faithful port of schema.sql (D1).
--
-- Faithful on purpose. Moving off D1 and changing what the data looks like are
-- two risks; this migration takes only the first:
--   * timestamps stay TEXT in SQLite's 'YYYY-MM-DD HH:MM:SS' (UTC) shape, so the
--     API contract, the SPA and every string comparison in the SQL behave
--     exactly as on D1;
--   * flags stay 0/1 integers, JSON stays TEXT;
--   * INTEGER becomes bigint (SQLite integers are 64-bit), AUTOINCREMENT an
--     identity column (ids are preserved on import, see scripts/import-d1.ts);
--   * the same foreign keys, defaults and indexes as schema.sql.
-- Typed columns (timestamptz, boolean, jsonb) are a later, separate migration.
--
-- The database must be created with a C collation (initdb --locale=C.UTF-8) so
-- ORDER BY on text sorts by code point, like SQLite's BINARY collation.

-- SQLite's datetime('now' [, '<±N unit>']) as used by the Worker's SQL and its
-- tests. Returns the same text shape SQLite does, always in UTC.
CREATE OR REPLACE FUNCTION datetime(value text, modifier text DEFAULT NULL)
RETURNS text
LANGUAGE sql
STABLE
AS $$
  SELECT to_char(
    (CASE WHEN value = 'now' THEN now() ELSE value::timestamptz END) AT TIME ZONE 'UTC'
      + COALESCE(modifier::interval, interval '0'),
    'YYYY-MM-DD HH24:MI:SS'
  )
$$;

CREATE TABLE IF NOT EXISTS users (
  id             text PRIMARY KEY,                -- OAuth subject id (stable per user)
  username       text NOT NULL,                   -- raw OAuth (Nanako) username, refreshed on login
  display_name   text,                            -- user's chosen display name; NULL = use username
  avatar_url     text,
  email          text,
  is_participant bigint NOT NULL DEFAULT 0,       -- 上榜选手 (has a credit score)
  is_judge       bigint NOT NULL DEFAULT 0,       -- 可立案
  is_admin       bigint NOT NULL DEFAULT 0,
  score          bigint NOT NULL DEFAULT 100,     -- current credit, clamped 0..100
  created_at     text NOT NULL DEFAULT (datetime('now')),
  updated_at     text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS records (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id           text NOT NULL REFERENCES users(id),
  reporter_id          text NOT NULL REFERENCES users(id),
  type                 text NOT NULL,
  delta                bigint NOT NULL DEFAULT 0,
  note                 text,
  claim                text,
  claim_summary        text,
  classified_by        text,
  escalation_suggested bigint NOT NULL DEFAULT 0,
  session_id           bigint,
  statement            text,
  statement_at         text,
  appeal_reason        text,
  deadline_at          text,
  judging_started_at   text,
  verdict_source       text,
  verdict_headline     text,
  verdict_reason       text,
  verdict_factors      text,                      -- JSON array of {kind, text}
  status               text NOT NULL DEFAULT 'awaiting_statement',
  created_at           text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS score_events (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         text NOT NULL REFERENCES users(id),
  delta           bigint NOT NULL,
  reason          text NOT NULL,                  -- record:<id> | revoke:<id> | override:<id> | weekly_heal | admin_adjust
  resulting_score bigint NOT NULL,
  created_at      text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS weekly_heals (
  week_start text PRIMARY KEY,                    -- YYYY-MM-DD (local Monday)
  applied_at text NOT NULL DEFAULT (datetime('now')),
  affected   bigint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS ai_verdicts (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id      bigint NOT NULL REFERENCES records(id),
  kind           text NOT NULL DEFAULT 'sentence',
  provider       text NOT NULL,
  model          text NOT NULL,
  prompt_version text NOT NULL,
  raw_response   text,
  parsed_delta   bigint,
  applied_delta  bigint NOT NULL,
  clamped        bigint NOT NULL DEFAULT 0,
  confidence     double precision,
  latency_ms     bigint,
  error          text,
  created_at     text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS weekly_reports (
  week_start text PRIMARY KEY,
  stats_json text NOT NULL,
  narrative  text NOT NULL,
  source     text NOT NULL,                       -- ai | fallback
  created_at text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS app_settings (
  key        text PRIMARY KEY,
  value      text NOT NULL,
  updated_by text,
  updated_at text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS game_sessions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizer_id text NOT NULL REFERENCES users(id),
  title        text NOT NULL,
  game         text,
  starts_at    text NOT NULL,                     -- ISO 8601 UTC
  duration_min bigint,
  capacity     bigint,
  note         text,
  status       text NOT NULL DEFAULT 'open',      -- open | cancelled | settled
  settled_at   text,
  settled_by   text,
  created_at   text NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS session_players (
  session_id      bigint NOT NULL REFERENCES game_sessions(id),
  user_id         text NOT NULL REFERENCES users(id),
  rsvp            text NOT NULL DEFAULT 'going',  -- invited | going | maybe | out
  rsvp_at         text NOT NULL DEFAULT (datetime('now')),
  attendance      text,
  late_minutes    bigint,
  attendance_note text,
  record_id       bigint,
  PRIMARY KEY (session_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_records_subject    ON records(subject_id);
CREATE INDEX IF NOT EXISTS idx_records_created    ON records(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_records_status     ON records(status, deadline_at);
CREATE INDEX IF NOT EXISTS idx_records_session    ON records(session_id);
CREATE INDEX IF NOT EXISTS idx_events_user        ON score_events(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_users_participant  ON users(is_participant, score DESC);
CREATE INDEX IF NOT EXISTS idx_verdicts_record    ON ai_verdicts(record_id);
CREATE INDEX IF NOT EXISTS idx_verdicts_created   ON ai_verdicts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_verdicts_kind      ON ai_verdicts(kind, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_records_escalation ON records(escalation_suggested, status);
CREATE INDEX IF NOT EXISTS idx_sessions_starts    ON game_sessions(starts_at DESC);
CREATE INDEX IF NOT EXISTS idx_sessions_status    ON game_sessions(status, starts_at);
CREATE INDEX IF NOT EXISTS idx_players_user       ON session_players(user_id);
