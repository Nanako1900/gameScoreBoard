-- P4: Discord account binding. PostgreSQL-only — the Discord bot and the
-- binding routes run on the Node backend, never on the old Worker.
--
-- One Discord account ↔ one Nanako account, in both directions (PRIMARY KEY on
-- the Discord id, UNIQUE on the user). Deleting a user removes the binding.
-- Same conventions as 0001: TEXT timestamps in SQLite's shape, 0/1 flags.

CREATE TABLE IF NOT EXISTS discord_links (
  discord_user_id  text PRIMARY KEY CHECK (discord_user_id ~ '^[0-9]{17,20}$'),
  user_id          text NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  discord_username text NOT NULL,
  notify_dm        bigint NOT NULL DEFAULT 1,  -- may the bot DM this user (used from P5)
  linked_at        text NOT NULL DEFAULT (datetime('now')),
  updated_at       text NOT NULL DEFAULT (datetime('now'))
);

-- Every bind / rebind / unbind, kept even after the account is gone (no FK).
CREATE TABLE IF NOT EXISTS link_audit (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  action          text NOT NULL CHECK (action IN ('link', 'relink', 'unlink')),
  via             text NOT NULL CHECK (via IN ('web', 'discord', 'admin')),
  user_id         text,
  discord_user_id text NOT NULL,
  created_at      text NOT NULL DEFAULT (datetime('now'))
);

CREATE INDEX IF NOT EXISTS idx_link_audit_user ON link_audit(user_id, created_at);
